interface LanguageContextType {
  language: SupportedLanguage
  setLanguage: (lang: SupportedLanguage) => void
  t: (key: string) => string
}

const LanguageContext = createContext<LanguageContextType>({
  language: 'es',
  setLanguage: () => {},
  t: (key: string) => key,
})

const STORAGE_KEY = '@carga_app_language'

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLangState] = useState<SupportedLanguage>('es')

  useEffect(() => {
    AsyncStorage.getItem(STORAGE_KEY).then((saved: string | null) => {
      if (saved && UI_TRANSLATIONS[saved as SupportedLanguage]) {
        setLangState(saved as SupportedLanguage)
      }
    })
  }, [])

  const setLanguage = async (newLang: SupportedLanguage) => {
    setLangState(newLang)
    await AsyncStorage.setItem(STORAGE_KEY, newLang)
  }

  const t = (key: string): string => {
    const dict = UI_TRANSLATIONS[language] || UI_TRANSLATIONS['es']
    return dict[key] || UI_TRANSLATIONS['es'][key] || key
  }

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  return useContext(LanguageContext)
}
